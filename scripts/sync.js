// Copies the code shared with the desktop app into web/ so the web build is self-contained
// (Vercel deploys only this folder). Run after changing ../src or ../renderer: npm run sync
const fs = require('fs');
const path = require('path');

const web = path.join(__dirname, '..');
const root = path.join(web, '..');

const HEADER = (src) => `// GENERATED by web/scripts/sync.js from ${src} — edit the original, then run \`npm run sync\`.\n`;

function copy(from, to, transform = (s) => s, header = true) {
  const src = path.join(root, from);
  const dest = path.join(web, to);
  if (!fs.existsSync(src)) throw new Error(`Missing ${src}`);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  let text = transform(fs.readFileSync(src, 'utf8'));
  if (header && /\.(js|css)$/.test(to)) text = (to.endsWith('.css') ? `/* ${HEADER(from).slice(3).trim()} */\n` : HEADER(from)) + text;
  fs.writeFileSync(dest, text);
  console.log(`  ${from} -> web/${to}`);
}

console.log('Syncing shared code into web/ …');

// server-side modules
copy('src/ai.js', 'lib/shared/ai.js');
copy('src/templates.js', 'lib/shared/templates.js');
copy('src/baseResume.js', 'lib/shared/baseResume.js');

// UI
copy('renderer/app.js', 'public/app.js');
copy('renderer/combobox.js', 'public/combobox.js');
copy('renderer/profile-editor.js', 'public/profile-editor.js');
copy('renderer/styles.css', 'public/styles.css');
copy('renderer/app.html', 'public/app.html', (html) => {
  const csp = `default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; font-src 'self' data:; img-src 'self' data: blob:; frame-src 'self' blob: data: about:; object-src 'self' blob:; connect-src 'self'`;
  const out = html
    .replace(/<meta http-equiv="Content-Security-Policy" content="[^"]*">/, `<meta http-equiv="Content-Security-Policy" content="${csp}">`)
    .replace('<script src="combobox.js"></script>', '<script src="api-web.js"></script>\n  <script src="combobox.js"></script>');
  if (!out.includes('api-web.js')) throw new Error('Could not inject api-web.js into app.html');
  return `<!-- GENERATED by web/scripts/sync.js from renderer/app.html — edit the original, then run npm run sync -->\n${out}`;
}, false);

console.log('Done.');
